#!/usr/bin/env python3
"""bin2c.py IN OUT NAME - a binary file as a C array (const: it stays in the calculator's flash)."""
import sys
data = open(sys.argv[1], 'rb').read()
name = sys.argv[3]
with open(sys.argv[2], 'w') as f:
    f.write('/* generated by tools/bin2c.py from %s: do not edit */\n#include <stdint.h>\n' % sys.argv[1])
    f.write('const uint8_t %s[%d] = {\n' % (name, len(data)))
    for i in range(0, len(data), 16):
        f.write('  ' + ', '.join('0x%02x' % b for b in data[i:i + 16]) + ',\n')
    f.write('};\n')
